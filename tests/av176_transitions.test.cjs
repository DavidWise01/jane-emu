'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {makeDetector,SCHEMA}=require('../dashboard/av176_transitions.js');
const d=makeDetector({minFrames:3});
const c={root:'run-a',rom:'rom-a'};
assert.equal(d.observe({frame:1,hash:'title'},c),null);
assert.equal(d.observe({frame:2,hash:'title'},c),null);
let e=d.observe({frame:3,hash:'title'},c);
assert.equal(e.type,'stable_screen_candidate');assert.equal(e.label,null);
assert.equal(d.observe({frame:4,hash:'title'},c),null);
assert.equal(d.labelCurrent('title').label,'title');
assert.throws(()=>d.labelCurrent('victory'));
d.observe({frame:5,hash:'game'},c);d.observe({frame:6,hash:'game'},c);
e=d.observe({frame:7,hash:'game'},c);assert.equal(e.label,null);
assert.equal(d.labelCurrent('gameplay').label,'gameplay');
d.observe({frame:8,hash:'title'},c);d.observe({frame:9,hash:'title'},c);
e=d.observe({frame:10,hash:'title'},c);assert.equal(e.label,'title');
assert.equal(d.observe({frame:10,hash:'title'},c),null);
assert.equal(d.observe({frame:11,hash:'title'},{root:'run-b',rom:'rom-a'}),null);
assert.throws(()=>d.labelCurrent('gameplay'),'new root must reset stability');
d.observe({frame:12,hash:'title'},{root:'run-b',rom:'rom-a'});
e=d.observe({frame:13,hash:'title'},{root:'run-b',rom:'rom-a'});assert.equal(e.label,'title');
d.observe({frame:14,hash:'title'},{root:'run-c',rom:'rom-b'});
d.observe({frame:15,hash:'title'},{root:'run-c',rom:'rom-b'});
e=d.observe({frame:16,hash:'title'},{root:'run-c',rom:'rom-b'});assert.equal(e.label,null,'labels must not cross cartridges');
const data=JSON.parse(d.exportJSON());assert.equal(data.schema,SCHEMA);
assert.equal(data.caveat.includes('not independently verified'),true);
const arena=fs.readFileSync(path.join(__dirname,'../dashboard/arena.html'),'utf8');
assert.match(arena,/<script src="\.\/av176_transitions\.js"><\/script>/);
assert.match(arena,/<iframe[^>]*id="game"/);
new vm.Script(fs.readFileSync(path.join(__dirname,'../dashboard/av176_transitions.js'),'utf8'));
console.log('AV-176 candidate transition, label isolation, reset and arena wiring tests passed');
