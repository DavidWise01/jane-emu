'use strict';
const assert=require('node:assert/strict');
const {create}=require('../dashboard/av208_adaptive_gameplay.js');
const p=create(),acts=['RIGHT','LEFT','A','B','START'];
const x=(frame,px,palette,actor='JANE',extra={})=>({root:'one-root',rom:'homebrew',actor,
 frame,mode:1,x:px,palette,actions:acts,...extra});
let offer=p.offer(x(10,120,0x30));assert.deepEqual(offer,{button:'RIGHT',hold:8});
assert.equal(p.offer(x(11,120,0x30)),null,'must not double-offer pending action');
assert.equal(p.complete({...x(18,120,0x30),button:'RIGHT'}),false,'unchanged RAM not success');
assert.equal(p.snapshot().holds.RIGHT,11,'failed movement increases duration');
offer=p.offer(x(20,120,0x30));assert.deepEqual(offer,{button:'RIGHT',hold:11});
assert.equal(p.complete({...x(32,136,0x30),button:'RIGHT'}),true);
assert.equal(p.snapshot().holds.RIGHT,10,'effective action shortens hold');
assert.equal(p.offer(x(33,136,0x30)).button,'A');
assert.equal(p.complete({...x(42,136,0x16),button:'A'}),true);
assert.equal(p.offer(x(43,136,0x16)).button,'LEFT');
assert.equal(p.complete({...x(52,104,0x16),button:'LEFT'}),true);
assert.equal(p.offer(x(53,104,0x16)).button,'B');
assert.equal(p.complete({...x(61,104,0x2a),button:'B'}),true);
assert.equal(p.snapshot().laps,1,'one lap requires real goal state progression');
assert.equal(p.offer(x(62,104,0x2a)).button,'RIGHT');
assert.equal(p.complete({...x(65,150,0x2a, 'TOPH'),button:'RIGHT'}),false,'other owner cannot complete');
assert.equal(p.offer(x(66,120,0x30,'TOPH')).button,'RIGHT','owner change resets independent adaptation');
assert.equal(p.snapshot().laps,0);
assert.equal(p.complete({...x(70,140,0x30,'TOPH',{button:'LEFT'})}),false,'wrong button forbidden');
assert.equal(p.complete({...x(70,140,0x30,'TOPH',{button:'RIGHT'})}),true);
assert.equal(p.offer(x(71,140,0x30,'TOPH',{mode:2})),null,'defeat prevents gameplay offer');
p.cancel('defeat');
assert.equal(p.snapshot().pending,null);
assert.equal(p.offer(x(2,120,0x30,'TOPH')).button,'RIGHT','clock rewind safely resets');
assert.equal(p.snapshot().holds.RIGHT,8,'clock rewind resets adaptive timing');
console.log('AV-208 adaptive NES policy functional assertions passed (controlled RAM inputs only)');
