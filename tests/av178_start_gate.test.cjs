'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {create,SCHEMA}=require('../dashboard/av178_start_gate.js');
const g=create({maxAttempts:3,cooldown:180});
const base={root:'r1',rom:'rom1',actor:'JANE',label:'title',enabled:true};
assert.equal(g.observe({...base,frame:0,enabled:false}).decision,'abstain');
assert.equal(g.observe({...base,frame:1,label:null}).decision,'abstain');
assert.equal(g.observe({...base,frame:2,actor:'TOPH'}).decision,'abstain');
assert.equal(g.observe({...base,frame:3}).decision,'request-start');
assert.equal(g.observe({...base,frame:4}).reason,'cooldown');
assert.equal(g.observe({...base,frame:183}).decision,'request-start');
assert.equal(g.observe({...base,frame:363}).decision,'request-start');
assert.equal(g.observe({...base,frame:543}).reason,'attempts-exhausted');
assert.equal(g.snapshot().attempts,3);
assert.equal(g.observe({...base,frame:544,label:'gameplay',playing:true}).reason,'gameplay-detected');
assert.equal(g.observe({...base,frame:900}).reason,'halted-until-new-session');
assert.equal(g.observe({...base,root:'r2',frame:0}).decision,'request-start');
assert.equal(g.observe({...base,root:'r2',frame:1,rom:'unloaded'}).reason,'unloaded-or-invalid');
assert.equal(JSON.parse(g.exportJSON()).schema,SCHEMA);
assert.equal(g.snapshot().events.filter(e=>e.kind==='start_requested').length,4);
const arena=fs.readFileSync(path.join(__dirname,'../dashboard/arena.html'),'utf8');
assert.ok(arena.includes('<script src="./av178_start_gate.js"></script>'));
assert.ok(arena.includes('<iframe id="game"'));
assert.ok(arena.includes('setInterval(sample,500);renderPlayers();init()'));
new vm.Script(fs.readFileSync(path.join(__dirname,'../dashboard/av178_start_gate.js'),'utf8'));
console.log('AV-178 deterministic START bounds, role gating, cooldown, halt, reset and arena boot passed');
