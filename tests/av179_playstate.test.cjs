'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {create,SCHEMA}=require('../dashboard/av179_playstate.js');
const d=create({stallMs:2000,stillSamples:3});
function sample(at,frame,extra={}){return d.classify({at,frame,root:'run-a',rom:'rom-a',...extra});}
assert.equal(d.classify({at:0,root:'run-a',rom:'unloaded',frame:0}).state,'UNLOADED');
assert.equal(sample(100,0).state,'ACTIVE_UNCLASSIFIED');
assert.equal(sample(500,1,{delta:.7}).state,'ACTIVE_UNCLASSIFIED','animated title cannot become gameplay without label');
assert.equal(sample(800,2,{label:'gameplay',labelCurrent:false,delta:.2}).state,'ACTIVE_UNCLASSIFIED','untrusted labels ignored');
assert.equal(sample(1100,3,{label:'title',labelCurrent:true,delta:.03}).state,'MENU');
assert.equal(sample(1300,4,{label:'gameplay',labelCurrent:true,delta:.2}).state,'PLAYING_LABELED');
assert.equal(d.snapshot().gameplayVerified,false);
assert.equal(sample(1500,5,{label:'game_over',labelCurrent:true}).state,'GAME_OVER');
assert.equal(sample(1700,6,{label:'recovery',labelCurrent:true}).state,'RECOVERY');
assert.equal(sample(1900,7).state,'ACTIVE_UNCLASSIFIED');
assert.equal(sample(2200,8,{delta:0}).state,'ACTIVE_UNCLASSIFIED');
assert.equal(sample(2500,9,{delta:0}).state,'ACTIVE_UNCLASSIFIED');
assert.equal(sample(2800,10,{delta:0}).state,'IDLE_CANDIDATE');
assert.equal(sample(3000,11,{delta:.1}).state,'ACTIVE_UNCLASSIFIED');
assert.equal(sample(5200,11).state,'STALLED','frame clock stall');
assert.equal(sample(5500,12).state,'ACTIVE_UNCLASSIFIED','advancing frame recovers from stall');
assert.equal(d.classify({at:5600,root:'run-b',rom:'rom-a',frame:1}).state,'ACTIVE_UNCLASSIFIED','session resets');
assert.equal(d.classify({at:5700,root:'run-b',rom:'rom-b',frame:2}).rom,'rom-b');
assert.equal(d.classify({at:5700,root:'run-b',rom:'rom-b',frame:2}).state,'UNKNOWN');
assert.equal(d.classify({at:5800,root:'run-b',rom:'rom-b',frame:null}).state,'UNKNOWN');
const exportData=JSON.parse(d.exportJSON());
assert.equal(exportData.schema,SCHEMA);
assert.equal(exportData.gameplayVerified,false);
assert.ok(exportData.events.some(e=>e.state==='STALLED'));
const js=fs.readFileSync(path.join(__dirname,'../dashboard/av179_playstate.js'),'utf8');new vm.Script(js);
const html=fs.readFileSync(path.join(__dirname,'../dashboard/arena.html'),'utf8');
assert.ok(html.includes('<script src="./av179_playstate.js"></script>'));
assert.ok(html.includes('<iframe id="game"'));
assert.ok(html.includes('setInterval(sample,500);renderPlayers();init()'));
console.log('AV-179 gameplay/idle/stall classifier tests passed');
