'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {create,ORDER,SCHEMA}=require('../dashboard/av182_handoff.js');
const test=create({timeoutMs:1200});
const a={ok:true,root:'r1',rom:'m1',frame:100,from:'JANE',to:'TOPH',at:0};
assert.deepEqual(ORDER,['JANE','TOPH','PATRICIA']);
assert.equal(test.begin({...a,to:'PATRICIA'}).accepted,false);
assert.equal(test.begin(a).accepted,true);
assert.equal(test.observe({root:'r1',rom:'m1',actor:'TOPH',frame:100,running:true,at:100}),null);
let result=test.observe({root:'r1',rom:'m1',actor:'TOPH',frame:120,running:true,at:150});
assert.equal(result.kind,'frame_continuity_observed');assert.equal(result.delta,20);
assert.equal(test.begin({...a,from:'TOPH',to:'PATRICIA',frame:120,at:200}).accepted,true);
result=test.observe({root:'r1',rom:'m1',actor:'PATRICIA',frame:121,running:true,at:250});
assert.equal(result.kind,'frame_continuity_observed');
assert.equal(test.begin({...a,from:'PATRICIA',to:'JANE',frame:121,at:300}).accepted,true);
result=test.observe({root:'r1',rom:'m1',actor:'JANE',frame:122,running:true,at:350});
assert.equal(result.kind,'frame_continuity_observed');
test.begin({...a,frame:200,at:400});result=test.observe({root:'r2',rom:'m1',actor:'TOPH',frame:201,running:true,at:450});
assert.equal(result.kind,'continuity_failed');
test.begin({...a,frame:200,at:500});result=test.observe({root:'r1',rom:'m1',actor:'TOPH',frame:199,running:true,at:550});
assert.equal(result.kind,'continuity_failed');
test.begin({...a,frame:200,at:600});
result=test.observe({root:'r1',rom:'m1',actor:'TOPH',frame:200,running:false,at:1900});
assert.equal(result.kind,'continuity_timeout');
assert.equal(test.snapshot().pending,null);
assert.equal(test.snapshot().liveROMVerified,false);
assert.equal(JSON.parse(test.exportJSON()).schema,SCHEMA);
new vm.Script(fs.readFileSync(path.join(__dirname,'../dashboard/av182_handoff.js'),'utf8'));
const page=fs.readFileSync(path.join(__dirname,'../dashboard/arena.html'),'utf8');
assert.ok(page.includes('<script src="./av182_handoff.js"></script>'));
assert.ok(page.includes('jane-handoff-accepted'));
assert.ok(page.includes('<iframe id="game"'));
assert.ok(page.includes('setInterval(sample,500);renderPlayers();init()'));
console.log('AV-182 deterministic handoff order and frame continuity tests passed');
