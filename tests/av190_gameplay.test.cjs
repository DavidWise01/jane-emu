'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {create,ORDER,SCHEMA}=require('../dashboard/av190_gameplay.js');
const p=create({interval:18});
const base={root:'r',rom:'game.nes',actor:'JANE',stage:'playing',actions:['RIGHT','LEFT','UP','DOWN','A','B']};
assert.deepEqual(ORDER,['RIGHT','LEFT','UP','DOWN','A','B']);
assert.equal(p.offer({...base,frame:1,stage:'title menu'}),null,'original START owner retains menu');
assert.equal(p.offer({...base,frame:1,stage:'game over'}),null,'recovery retains game-over');
assert.equal(p.offer({...base,frame:1,rom:'unloaded'}),null);
assert.equal(p.offer({...base,frame:1}), 'RIGHT');
assert.equal(p.offer({...base,frame:2}), 'RIGHT','stable choice within one interval');
assert.equal(p.result({...base,frame:4,button:'RIGHT',delta:0,completed:false}),false,'queued input is not completed');
assert.equal(p.result({...base,frame:4,button:'RIGHT',delta:0,completed:true}),true);
assert.equal(p.offer({...base,frame:18}),'LEFT','untried legal action precedes trained zero-progress action');
assert.equal(p.result({...base,frame:20,button:'LEFT',delta:2,completed:true}),true);
assert.equal(p.result({...base,frame:20,button:'LEFT',delta:2,completed:true}),false,'duplicate trial rejected');
assert.equal(p.offer({...base,frame:36}),'UP','all actions get bounded exploration');
assert.equal(p.offer({...base,frame:54}),'DOWN');
assert.equal(p.offer({...base,frame:72}),'A');
assert.equal(p.offer({...base,frame:90}),'B');
assert.equal(p.offer({...base,frame:108}),'LEFT','observed delta changes deterministic preference');
assert.equal(p.offer({...base,actor:'TOPH',frame:109}),'RIGHT','handoff creates separate per-actor session');
assert.equal(p.offer({...base,actor:'PATRICIA',frame:109}),'RIGHT');
assert.equal(p.offer({...base,actor:'PATRICIA',frame:1}),'RIGHT','frame rewind resets per-session policy');
p.setEnabled(false);assert.equal(p.offer({...base,frame:120}),null,'manual disable restores native fallback');
assert.equal(p.snapshot().schema,SCHEMA);
const page=fs.readFileSync(path.join(__dirname,'../dashboard/arena.html'),'utf8');
assert.ok(page.includes('<script src="./av190_gameplay.js"></script>'));
assert.ok(page.includes('JANE_AV190_MECHANICS?.offer?.({root:ctx?.root,rom:ctx?.rom,actor:ctx?.actor'));
assert.ok(page.includes('JANE_AV190_MECHANICS?.result?.({root:ctx.root,rom:romID,actor:ctx.actor'));
assert.ok(page.includes('JANE_PLAYER_STATE?.switchTo'));
assert.ok(page.includes('setInterval(sample,500);renderPlayers();init()'));
assert.ok(page.includes('<script src="./av186_three_tools.js"></script>'));
new vm.Script(fs.readFileSync(path.join(__dirname,'../dashboard/av190_gameplay.js'),'utf8'));
console.log('AV-190 authoritative NES movement/attack mechanics and completed-trial adaptation tests passed');
