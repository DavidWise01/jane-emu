'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {create,SCHEMA}=require('../dashboard/av189_runtime.js');
const monitor=create();
assert.equal(monitor.snapshot().state,'BOOTING');
monitor.notice({state:'ROM_QUEUED',session:'r1',reason:'queued',at:100});
assert.equal(monitor.snapshot().state,'ROM_QUEUED');
monitor.notice({state:'ROM_DELIVERED',session:'r1',at:120});
monitor.frame({session:'r1',frame:10,running:true,at:150});
monitor.frame({session:'other',frame:1000,running:true,at:160});
assert.equal(monitor.snapshot().advanced,0,'other session not counted');
monitor.frame({session:'r1',frame:129,running:true,at:170});
assert.equal(monitor.snapshot().advanced,119);
monitor.frame({session:'r1',frame:130,running:true,at:180});
assert.equal(monitor.snapshot().state,'ROM_RUNNING');
assert.equal(monitor.snapshot().browserGameplayVerified,false);
monitor.notice({state:'BOOT_ERROR',reason:'injected script failure',at:200});
monitor.notice({state:'FALLBACK_READY',reason:'raw NES cabinet ready',at:210});
assert.equal(monitor.snapshot().state,'FALLBACK_READY','original fallback must be usable');
monitor.notice({state:'ROM_DELIVERED',session:'r2',at:220});
monitor.frame({session:'r2',frame:0,running:true,at:221});
assert.equal(monitor.snapshot().advanced,0,'new cartridge progress must reset');
monitor.notice({state:'ROM_ERROR',reason:'bad iNES header',at:230});
assert.equal(monitor.snapshot().state,'ROM_ERROR');
monitor.notice({state:'ROM_RUNNING',session:'r1',at:240});
assert.equal(monitor.snapshot().state,'ROM_ERROR','old session cannot claim success');
assert.equal(JSON.parse(monitor.exportJSON()).schema,SCHEMA);
const page=fs.readFileSync(path.join(__dirname,'../dashboard/arena.html'),'utf8');
assert.ok(page.includes('<script src="./av189_runtime.js"></script>'));
assert.ok(page.includes("fetch(release,{cache:'no-store'})"),'fresh cartridge release, no sticky stale cache');
assert.ok(page.includes("runtimeNotice('FALLBACK_READY'"),'fallback must be observable');
assert.ok(page.includes("ready=!!w().document.getElementById('romInput');"));
assert.ok(page.includes("if(pendingNESFile){const queued=pendingNESFile;pendingNESFile=null;setTimeout(()=>load(queued),0)}"),'fallback must flush early queued ROM');
assert.ok(page.includes("runtimeNotice('ROM_DELIVERED'"),'must report actual file delivery');
assert.ok(page.includes("window.JANE_AV189_RUNTIME?.frame?.({frame,session:gameRoot,running:s.running===true})"));
assert.ok(page.includes('JANE_PLAYER_STATE?.switchTo'));
assert.ok(page.includes('<script src="./av186_three_tools.js"></script>'));
assert.ok(page.includes('setInterval(sample,500);renderPlayers();init()'));
new vm.Script(fs.readFileSync(path.join(__dirname,'../dashboard/av189_runtime.js'),'utf8'));
console.log('AV-189 fail-closed runtime readiness, fallback ROM loading, session frame and three-tool invariants passed');
