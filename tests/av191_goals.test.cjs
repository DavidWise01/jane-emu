'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {create}=require('../dashboard/av191_goals.js');
const {create:mechanics}=require('../dashboard/av190_gameplay.js');
const g=create({stalledLimit:3}),ctx={root:'session-1',rom:'game.nes',actor:'JANE'};
const b=frame=>g.biases({...ctx,frame});
assert.equal(b(0).RIGHT,0);
assert.equal(g.feedback({...ctx,frame:10,button:'RIGHT',completed:false,delta:0}),false,'queued input cannot train');
for(let i=1;i<=3;i++)assert.equal(g.feedback({...ctx,frame:i*10,button:'RIGHT',completed:true,delta:0}),true);
assert.equal(b(31).RIGHT,-2.25,'three zero-progress tries yield bounded stall penalty');
assert.equal(g.feedback({...ctx,frame:40,button:'A',delta:10,completed:true}),true);
assert.ok(b(41).A>0,'observed positive change rewards attack');
assert.equal(g.feedback({...ctx,frame:50,button:'B',delta:0,lifeLost:true,completed:true}),true);
assert.ok(b(51).B<=-2,'explicit loss penalizes harmful action');
assert.equal(g.feedback({...ctx,frame:49,button:'A',delta:8,completed:true}),false,'stale frame not counted');
assert.equal(b(52).RIGHT,-2.25);
assert.equal(g.biases({...ctx,actor:'TOPH',frame:53}).RIGHT,0,'handoff resets context');
assert.equal(g.biases({...ctx,rom:'other.nes',actor:'TOPH',frame:0}).RIGHT,0,'ROM change resets context');
const p=mechanics({interval:18});
const c={root:'r',rom:'game.nes',actor:'JANE',stage:'playing',frame:18,actions:['RIGHT','LEFT','A']};
assert.equal(p.offer({...c,bias:{RIGHT:-4,LEFT:2,A:0}}),'LEFT','bias affects existing controller ranking');
assert.equal(p.offer({...c,frame:19,bias:{RIGHT:2,LEFT:-4,A:2}}),'LEFT','stable action within frame window');
assert.equal(p.offer({...c,frame:36,stage:'title menu'}),null,'START owner retains menu');
assert.equal(p.offer({...c,frame:36,stage:'game over'}),null,'defeat owner retains game over');
const html=fs.readFileSync(path.join(__dirname,'../dashboard/arena.html'),'utf8');
assert.ok(html.includes('<script src="./av191_goals.js"></script>'));
assert.ok(html.includes('JANE_AV191_GOALS?.biases?.('));
assert.ok(html.includes('JANE_AV191_GOALS?.feedback?.('));
assert.ok(html.includes('JANE_AV190_MECHANICS?.offer?.('));
assert.ok(html.includes('<iframe id="game"'));
assert.ok(html.includes('<script src="./av186_three_tools.js"></script>'));
new vm.Script(fs.readFileSync(path.join(__dirname,'../dashboard/av191_goals.js'),'utf8'));
console.log('AV-191 NES goal feedback, stall-avoidance, scoped action ranking and original controller tests passed');
