'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {choose,makeBridge,SCHEMA}=require('../dashboard/av180_best_action.js');
const ctx={root:'r',rom:'NES-test',actor:'JANE',frame:100,state:'ACTIVE_UNCLASSIFIED'};
const c=(action,priority,over={})=>({action,priority,eligible:true,owner:'JANE',rom:'NES-test',source:'test',...over});
assert.equal(choose([c('B',10),c('A',20)],ctx).action,'A','highest priority');
assert.equal(choose([c('B',20),c('A',20)],ctx).action,'A','fixed tie-break');
assert.equal(choose([c('A',100,{owner:'TOPH'}),c('B',20)],ctx).action,'B','no cross-controller offer');
assert.equal(choose([c('SELECT',50),c('START',99)],ctx).action,'SELECT','START requires confirmed menu');
assert.equal(choose([c('START',99)],{...ctx,state:'MENU'}).action,'START');
assert.equal(choose([c('A',99)],{...ctx,state:'STALLED'}).action,null);
assert.equal(choose([c('A',99)],{...ctx,rom:'unloaded'}).reason,'no-active-owner');
assert.equal(choose([c('A',101),c('B',-1),c('UP',NaN)],ctx).action,null,'reject invalid priority');
assert.equal(choose([c('UP',2,{eligible:false})],ctx).eligible,0);
const b=makeBridge();assert.equal(b.decide([c('A',20)],ctx).action,null,'off by default');
b.setEnabled(true);assert.equal(b.decide([c('A',20)],ctx).action,'A');
assert.equal(b.status().history.length,2);
assert.equal(JSON.parse(b.exportJSON()).schema,SCHEMA);
const page=fs.readFileSync(path.join(__dirname,'../dashboard/arena.html'),'utf8');
assert.ok(page.includes('<script src="./av180_best_action.js"></script>'));
assert.ok(page.includes('JANE_AV180_BRIDGE'));
assert.ok(page.includes('<iframe id="game"'));
assert.ok(page.includes('setInterval(sample,500);renderPlayers();init()'));
new vm.Script(fs.readFileSync(path.join(__dirname,'../dashboard/av180_best_action.js'),'utf8'));
console.log('AV-180 deterministic eligible-action selector, NES owner and fallback tests passed');
