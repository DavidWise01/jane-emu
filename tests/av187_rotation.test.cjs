'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {create,ORDER,SCHEMA}=require('../dashboard/av187_rotation.js');
const m=create({minAdvance:60,timeoutMs:1500});
const step=(actor,frame,at,other={})=>m.observe({root:'r1',rom:'demo.nes',actor,frame,at,running:true,...other});
const handoff=(from,to,frame,at,other={})=>m.accepted({ok:true,root:'r1',rom:'demo.nes',from,to,actor:to,frame,at,...other});
assert.deepEqual(ORDER,['JANE','TOPH','PATRICIA','JANE']);
assert.equal(step('JANE',100,0).steps.length,0);
assert.equal(handoff('JANE','TOPH',100,100).accepted,true);
assert.equal(step('TOPH',159,500).steps.length,0,'59 frames insufficient');
assert.equal(step('TOPH',160,900).steps.length,1);
assert.equal(handoff('TOPH','PATRICIA',160,1000).accepted,true);
assert.equal(step('PATRICIA',220,1100).steps.length,2);
assert.equal(handoff('PATRICIA','JANE',220,1200).accepted,true);
let result=step('JANE',280,1300);
assert.equal(result.steps.length,3);assert.equal(result.fullRotationObserved,true);
assert.equal(result.actualGameplayVerified,false);
assert.equal(result.phaseGateVerified,false);
assert.equal(handoff('JANE','TOPH',280,1400).accepted,false,'no duplicate cycle evidence');
const separate=create({minAdvance:60,timeoutMs:1500});
separate.observe({root:'r1',rom:'demo.nes',actor:'JANE',frame:0,at:0,running:true});
assert.equal(separate.accepted({ok:true,root:'r2',rom:'demo.nes',actor:'TOPH',from:'JANE',to:'TOPH',frame:0,at:10}).accepted,false,'reject different root');
separate.accepted({ok:true,root:'r1',rom:'demo.nes',actor:'TOPH',from:'JANE',to:'TOPH',frame:0,at:10});
const interrupted=separate.observe({root:'r1',rom:'demo.nes',actor:'TOPH',frame:0,at:2000,running:false});
assert.equal(interrupted.failed,true);assert.equal(interrupted.fullRotationObserved,false);
const rewind=create();
rewind.observe({root:'r1',rom:'demo.nes',actor:'JANE',frame:100,at:100,running:true});
rewind.accepted({ok:true,root:'r1',rom:'demo.nes',actor:'TOPH',from:'JANE',to:'TOPH',frame:100,at:200});
assert.equal(rewind.observe({root:'r1',rom:'demo.nes',actor:'TOPH',frame:2,at:300,running:true}).steps.length,0,'reset clears pending');
const order=create();order.observe({root:'r1',rom:'demo.nes',actor:'JANE',frame:0,at:0,running:true});
assert.equal(order.accepted({ok:true,root:'r1',rom:'demo.nes',actor:'PATRICIA',from:'JANE',to:'PATRICIA',frame:0,at:1}).accepted,false);
assert.equal(order.snapshot().failed,true);
assert.equal(JSON.parse(m.exportJSON()).schema,SCHEMA);
new vm.Script(fs.readFileSync(path.join(__dirname,'../dashboard/av187_rotation.js'),'utf8'));
const html=fs.readFileSync(path.join(__dirname,'../dashboard/arena.html'),'utf8');
assert.ok(html.includes('<script src="./av187_rotation.js"></script>'));
assert.match(html,/<iframe[^>]*id="game"/);
assert.ok(html.includes('jane-handoff-accepted'));
assert.ok(html.includes('setInterval(sample,500);renderPlayers();init()'));
assert.ok(html.includes('<script src="./av186_three_tools.js"></script>'));
console.log('AV-187 full ordered rotation, same-ROM clock, failure, reset and 3-tab retention passed');
