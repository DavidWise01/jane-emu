'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {create,SCHEMA}=require('../dashboard/av183_endurance.js');
const m=create({stallMs:2000,maxEvents:12});
const base={root:'run-a',rom:'rom-a',actor:'JANE'};
let s=m.observe({...base,at:0,frame:0});
assert.equal(s.session.advanced,0);
s=m.observe({...base,at:500,frame:60});
assert.equal(s.session.advanced,60);
assert.equal(s.session.stalls,0);
s=m.observe({...base,at:2700,frame:60});
assert.equal(s.session.stalls,1);
assert.equal(s.session.clockFrozen,true);
s=m.observe({...base,at:2800,frame:70});
assert.equal(s.session.clockFrozen,false);
assert.equal(s.session.advanced,70);
s=m.observe({...base,actor:'TOPH',frame:90,at:3100,handoffAccepted:true,handoffFrom:'JANE',handoffTo:'TOPH'});
assert.equal(s.session.handoffs,1);
s=m.observe({...base,actor:'PATRICIA',frame:110,at:3400,handoffAccepted:true,handoffFrom:'TOPH',handoffTo:'PATRICIA',recoveryRequested:true});
assert.equal(s.session.recoveries,1);
assert.equal(s.session.handoffs,2);
assert.equal(s.threePlayerCycleSeen,true);
assert.equal(s.liveGameplayVerified,false);
assert.equal(s.endurancePass,false);
s=m.observe({...base,actor:'JANE',frame:120,at:3800});
assert.equal(s.session.handoffs,2,'unconfirmed owner change is not counted');
assert.ok(s.events.some(e=>e.kind==='owner_change_unconfirmed'));
s=m.observe({...base,actor:'JANE',frame:0,at:4000});
assert.equal(s.session.advanced,0,'frame rollback starts a new session scope');
assert.equal(s.session.handoffs,0);
assert.equal(m.observe({...base,rom:'unloaded',at:4100,frame:1}).session.rom,'rom-a','unloaded does not replace state');
for(let i=1;i<=30;i++)m.observe({...base,at:4100+i*100,frame:i});
assert.ok(m.snapshot().events.length<=12);
const e=JSON.parse(m.exportJSON());assert.equal(e.schema,SCHEMA);assert.equal(e.liveGameplayVerified,false);
new vm.Script(fs.readFileSync(path.join(__dirname,'../dashboard/av183_endurance.js'),'utf8'));
const page=fs.readFileSync(path.join(__dirname,'../dashboard/arena.html'),'utf8');
assert.ok(page.includes('<script src="./av183_endurance.js"></script>'));
assert.ok(page.includes('<iframe id="game"'));
assert.ok(page.includes('setInterval(sample,500);renderPlayers();init()'));
console.log('AV-183 endurance, stalls, resumes, handoffs, recovery and arena preflight passed');
