'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const api=require('../dashboard/av175_playability.js');
const log=api.makeRecorder(()=> '2026-11-21T00:00:00.000Z');
log.observe({root:'a',actor:'JANE',rom:'unloaded',frame:0});
log.observe({root:'a',actor:'JANE',rom:'test-rom',frame:0});
assert.equal(log.snapshot().frameProgressSeen,false);
log.observe({root:'a',actor:'JANE',rom:'test-rom',frame:60,running:true});
assert.equal(log.snapshot().frameProgressSeen,true);
log.observe({root:'a',actor:'TOPH',rom:'test-rom',frame:61,running:true});
assert.ok(log.snapshot().events.some(e=>e.kind==='handoff_observed'));
log.observe({root:'b',actor:'TOPH',rom:'test-rom',frame:2,running:true});
assert.ok(log.snapshot().events.some(e=>e.kind==='frame_reset_observed'));
log.annotate('start_sent','press');
assert.ok(log.snapshot().events.some(e=>e.kind==='operator_start_sent'));
assert.throws(()=>log.annotate('definitely_passed'));
const serialized=log.exportJSON();
assert.equal(JSON.parse(serialized).schema,api.SCHEMA);
assert.equal(JSON.parse(serialized).caution.includes('not independently verified'),true);
const original=log.snapshot().events.length;
log.snapshot().events.push({fake:true});
assert.equal(log.snapshot().events.length,original);
const page=fs.readFileSync(path.join(__dirname,'../dashboard/arena.html'),'utf8');
assert.match(page,/<script src="\.\/av175_playability\.js"><\/script>/);
assert.match(page,/<iframe[^>]*id="game"/);
assert.match(page,/setInterval\(sample,500\);renderPlayers\(\);init\(\)/);
new vm.Script(fs.readFileSync(path.join(__dirname,'../dashboard/av175_playability.js'),'utf8'));
console.log('AV-175 recorder controls, evidence history, syntax and emulator preservation passed');
