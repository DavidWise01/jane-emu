'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {evaluate,SCHEMA,REQUIRED}=require('../dashboard/av188_acceptance.js');
const root='r1',rom='game.nes',context={root,rom,frame:4000};
const boot={session:{root,rom},bootFramesObserved:true,startActionObserved:true,postStartFramesObserved:true};
const rotation={root,rom,fullRotationObserved:true,failed:false};
const endurance={session:{root,rom,advanced:3600,stalls:0,clockFrozen:false},threePlayerCycleSeen:true};
const recovery={events:[{root,rom,kind:'start_recovery_requested',frame:1000},{root,rom,kind:'recovery_observed',frame:1500}]};
const playability={events:[{root,rom,kind:'operator_gameplay_seen'}]};
assert.equal(evaluate().signalsObserved,0);
let s=evaluate({context,boot,rotation,endurance,recovery,playability});
assert.equal(s.schema,SCHEMA);
assert.deepEqual(s.missing,[]);
assert.equal(s.signalsObserved,REQUIRED.length);
assert.equal(s.verdict,'READY_FOR_EXTERNAL_BROWSER_REVIEW');
assert.equal(s.liveGameplayVerified,false);
assert.equal(s.phaseGateVerified,false);
assert.equal(s.phase3Percent,0);
s=evaluate({context:{...context,rom:'other.nes'},boot,rotation,endurance,recovery,playability});
assert.equal(s.signalsObserved,0,'all telemetry isolated by ROM');
s=evaluate({context:{...context,root:'other'},boot,rotation,endurance,recovery,playability});
assert.equal(s.signalsObserved,0,'all telemetry isolated by root');
s=evaluate({context,boot,rotation,endurance,recovery:{events:[recovery.events[1],{...recovery.events[0],frame:2000}]},playability});
assert.equal(s.checks.recovery,false,'recovery return must occur after request');
s=evaluate({context,boot,rotation,endurance:{...endurance,session:{...endurance.session,stalls:1}},recovery,playability});
assert.equal(s.checks.endurance,false,'any stall prevents claimed clean endurance');
s=evaluate({context,boot,rotation,endurance,recovery,playability:{events:[]}});
assert.equal(s.checks.screenReview,false,'missing operator observation cannot pass screen review');
const page=fs.readFileSync(path.join(__dirname,'../dashboard/arena.html'),'utf8');
assert.ok(page.includes('<script src="./av188_acceptance.js"></script>'));
assert.ok(page.includes('<script src="./av186_three_tools.js"></script>'));
assert.ok(page.includes('<iframe id="game"'));
assert.ok(page.includes('setInterval(sample,500);renderPlayers();init()'));
new vm.Script(fs.readFileSync(path.join(__dirname,'../dashboard/av188_acceptance.js'),'utf8'));
console.log('AV-188 same-session endurance/recovery/rotation and fail-closed phase freeze passed');
