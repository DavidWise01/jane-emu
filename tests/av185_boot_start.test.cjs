'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {create,SCHEMA}=require('../dashboard/av185_boot_start.js');
const monitor=create({minFrames:120});
const ctx={root:'a',rom:'test.nes'};
assert.equal(monitor.snapshot().cartridgeObserved,false);
assert.equal(monitor.actionCompleted({...ctx,frame:0,button:'START',executed:true}),null,'no session, no borrowed START');
monitor.observe({...ctx,frame:0,running:true});
assert.equal(monitor.snapshot().cartridgeObserved,true);
monitor.observe({...ctx,frame:119,running:true});
assert.equal(monitor.snapshot().bootFramesObserved,false);
monitor.observe({...ctx,frame:120,running:true});
assert.equal(monitor.snapshot().bootFramesObserved,true);
monitor.actionCompleted({...ctx,frame:121,button:'A',executed:true});
assert.equal(monitor.snapshot().startActionObserved,false,'A is not START');
monitor.actionCompleted({...ctx,frame:121,button:'START',executed:false});
assert.equal(monitor.snapshot().startActionObserved,false,'queued START is not executed');
monitor.actionCompleted({...ctx,frame:121,button:'START',executed:true});
assert.equal(monitor.snapshot().startActionObserved,true);
monitor.observe({...ctx,frame:240,running:true});
assert.equal(monitor.snapshot().postStartFramesObserved,false);
monitor.observe({...ctx,frame:241,running:true});
assert.equal(monitor.snapshot().postStartFramesObserved,true);
assert.equal(monitor.snapshot().liveGamePlayableVerified,false,'still requires actual browser ROM review');
monitor.actionCompleted({...ctx,frame:250,button:'START',executed:true});
assert.equal(monitor.snapshot().events.filter(x=>x.kind==='emulator_start_action_completed').length,1);
monitor.observe({...ctx,root:'b',frame:0,running:true});
assert.equal(monitor.snapshot().startActionObserved,false,'new root cannot borrow START evidence');
assert.equal(monitor.snapshot().bootFramesObserved,false,'new root cannot borrow frames');
assert.equal(monitor.actionCompleted({...ctx,frame:1,button:'START',executed:true}),null,'old root cannot inject START');
monitor.observe({...ctx,root:'b',rom:'other.nes',frame:0,running:true});
assert.equal(monitor.snapshot().session.rom,'other.nes');
const exported=JSON.parse(monitor.exportJSON());
assert.equal(exported.schema,SCHEMA);
assert.equal(exported.liveGamePlayableVerified,false);
const page=fs.readFileSync(path.join(__dirname,'../dashboard/arena.html'),'utf8');
assert.match(page,/<script src="\.\/av185_boot_start\.js"><\/script>/);
assert.match(page,/JANE_AV185_FRAME\?\.\(\{rom:romID,frame\}\)/);
assert.match(page,/JANE_AV185_ACTION_COMPLETE\?\.\(\{rom:romID,frame,button:record\.button\}\)/);
assert.match(page,/<iframe[^>]*id="game"/);
assert.match(page,/setInterval\(sample,500\);renderPlayers\(\);init\(\)/);
new vm.Script(fs.readFileSync(path.join(__dirname,'../dashboard/av185_boot_start.js'),'utf8'));
console.log('AV-185 boot START executed-action and post-START frame evidence tests passed');
