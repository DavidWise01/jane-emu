'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {create,SCHEMA}=require('../dashboard/av181_recovery.js');
const gate=create({maxAttempts:2,cooldown:240});
const x={root:'run1',rom:'rom1',actor:'JANE',state:'GAME_OVER',confirmed:true,enabled:true};
assert.equal(gate.step({...x,frame:1,enabled:false}).reason,'disabled');
assert.equal(gate.step({...x,frame:2,actor:'TOPH'}).reason,'not-jane-owner');
assert.equal(gate.step({...x,frame:3,confirmed:false}).reason,'no-confirmed-game-over');
assert.equal(gate.step({...x,frame:4}).decision,'queue-existing-start');
assert.equal(gate.step({...x,frame:5}).reason,'cooldown');
assert.equal(gate.step({...x,frame:244}).decision,'queue-existing-start');
assert.equal(gate.step({...x,frame:484}).reason,'attempts-exhausted');
assert.equal(gate.snapshot().attempts,2);
assert.equal(gate.step({...x,frame:485,state:'PLAYING_LABELED'}).reason,'playing-observed');
assert.equal(gate.step({...x,frame:486}).reason,'episode-closed');
assert.equal(gate.step({...x,frame:1,root:'run2'}).decision,'queue-existing-start','new session restores budget');
assert.equal(gate.step({...x,frame:2,root:'run2',rom:'unloaded'}).reason,'no-valid-cartridge');
assert.equal(JSON.parse(gate.exportJSON()).schema,SCHEMA);
assert.equal(gate.snapshot().liveGameplayVerified,false);
const src=fs.readFileSync(path.join(__dirname,'../dashboard/av181_recovery.js'),'utf8');
new vm.Script(src);
const html=fs.readFileSync(path.join(__dirname,'../dashboard/arena.html'),'utf8');
assert.ok(html.includes('<script src="./av181_recovery.js"></script>'));
assert.ok(html.includes('<iframe id="game"'));
assert.ok(html.includes('setInterval(sample,500);renderPlayers();init()'));
console.log('AV-181 defeat recovery budget, owner, confirmation and persistence tests passed');
