'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {create,SCHEMA}=require('../dashboard/av192_timing.js');
const t=create();
const ctx={root:'r1',rom:'legal.nes',actor:'JANE'};
const selection=(button,frame,other={})=>({root:ctx.root,rom:ctx.rom,actor:ctx.actor,button,frame,...other});
const hold=(button,frame,other={})=>t.hold({...ctx,button,frame,selected:selection(button,frame),...other});
assert.equal(hold('RIGHT',100),10);
assert.equal(hold('A',101),5);
assert.equal(hold('B',102),5);
assert.equal(hold('UP',103),9);
assert.equal(t.hold({...ctx,button:'START',frame:104,selected:selection('START',104)}),null,'START must use native timing');
assert.equal(t.hold({...ctx,button:'A',frame:105,selected:selection('RIGHT',105)}),null,'not this policy selection');
assert.equal(t.hold({...ctx,button:'A',frame:105,selected:selection('A',104)}),null,'cannot change an older command');
assert.equal(t.hold({...ctx,button:'A',frame:105,selected:selection('A',105,{rom:'different.nes'})}),null);
assert.equal(t.feedback({...ctx,frame:110,button:'A',delta:0,completed:false}),false);
assert.equal(t.feedback({...ctx,frame:110,button:'A',delta:0,completed:true}),true);
assert.equal(hold('A',111),4,'zero-change attack gets shorter');
assert.equal(t.feedback({...ctx,frame:112,button:'A',delta:0,completed:true}),true);
assert.equal(hold('A',113),3,'clamped attack duration');
assert.equal(t.feedback({...ctx,frame:115,button:'A',delta:20,completed:true}),true);
assert.equal(hold('A',116),3,'successful attack is deliberately brief');
assert.equal(t.feedback({...ctx,frame:120,button:'RIGHT',delta:8,completed:true}),true);
assert.equal(hold('RIGHT',121),11,'successful movement can lengthen');
assert.equal(t.feedback({...ctx,frame:123,button:'RIGHT',delta:8,lifeLost:true,completed:true}),true);
assert.equal(hold('RIGHT',124),9,'observed life lost shortens exposure');
for(let i=1;i<=20;i++)t.feedback({...ctx,frame:124+i,button:'LEFT',delta:100,completed:true});
assert.ok(hold('LEFT',146)<=18,'movement has hard timing bound');
assert.equal(t.feedback({...ctx,frame:110,button:'A',delta:1,completed:true}),false,'stale trial must not count');
assert.equal(t.hold({...ctx,actor:'TOPH',button:'A',frame:147,selected:selection('A',147,{actor:'TOPH'})}),5,'player changes reset state');
assert.equal(t.hold({...ctx,actor:'TOPH',rom:'different.nes',button:'RIGHT',frame:0,selected:selection('RIGHT',0,{actor:'TOPH',rom:'different.nes'})}),10);
assert.equal(t.snapshot().gameplayVerified,false);
assert.equal(t.snapshot().schema,SCHEMA);
const page=fs.readFileSync(path.join(__dirname,'../dashboard/arena.html'),'utf8');
assert.ok(page.includes('<script src="./av192_timing.js"></script>'));
assert.ok(page.includes('JANE_AV192_TIMING?.hold?.('));
assert.ok(page.includes('JANE_AV192_TIMING?.feedback?.('));
assert.ok(page.includes('const frames=recovery?.hold||anticipatory?.hold||counterstrike?.hold||dreamTransfer?.hold||homeRecall?.hold||timed192||holdFrames(button)'));
assert.ok(page.includes('<script src="./av186_three_tools.js"></script>'));
assert.ok(page.includes('setInterval(sample,500);renderPlayers();init()'));
new vm.Script(fs.readFileSync(path.join(__dirname,'../dashboard/av192_timing.js'),'utf8'));
console.log('AV-192 bounded NES button timing, selection ownership, completed-trial feedback and three-tool retention passed');
